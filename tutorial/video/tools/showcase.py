#!/usr/bin/env python3
"""
The assistants' showcase clips (the animated WebP of «Try», in assistants/<Name>/src/*/Package/showcase, and Pip's in
samples/CharacterAssistant/Package/showcase) that the scenes use, as MP4 the video can play: python tools/showcase.py

Like icons.mjs, it collects them from the scenes (any "Lander/window.minimize" written in them), converts each one to
public/generated/showcase/<Name>/<clip>.mp4 (30 fps, twice the size) and writes their lengths in frames to
src/generated/showcase.ts. Run it after adding a clip to a scene.
"""
import io
import json
import re
import subprocess
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent.parent
FFMPEG = ROOT / "node_modules" / "@remotion" / "compositor-win32-x64-msvc" / "ffmpeg.exe"
FPS = 30
SCALE = 2

names = set()
for folder in (ROOT / "src", ROOT / "shorts"):
    for file in folder.rglob("*.ts*"):
        if "generated" in file.parts:
            continue
        names.update(re.findall(r"""["']((?:Lander|Kobii|Kumo|Pip)/[a-z][\w.]*)["']""", file.read_text(encoding="utf-8")))


def frames(webp: Path):
    """Each frame of the WebP with the moment it starts (ms), and the clip's total length (ms)."""
    im = Image.open(webp)
    out, t = [], 0
    for i in range(getattr(im, "n_frames", 1)):
        im.seek(i)
        out.append((t, im.convert("RGB").copy()))
        t += im.info.get("duration", 40) or 40
    return out, t


lengths = {}
for name in sorted(names):
    who, clip = name.split("/")
    # Pip, the example without code, lives in the repository; the others in assistants/ (their own repository).
    home = REPO / "samples" / "CharacterAssistant" if who == "Pip" else REPO / "assistants" / who / "src"
    found = list(home.glob(f"**/Package/showcase/{clip}.webp"))
    if not found:
        raise SystemExit(f"no clip {name}")
    src = found[0]
    dst = ROOT / "public" / "generated" / "showcase" / who / f"{clip}.mp4"
    shots, total = frames(src)
    count = max(1, round(total * FPS / 1000))
    lengths[name] = count
    if dst.exists() and dst.stat().st_mtime > src.stat().st_mtime:
        continue
    dst.parent.mkdir(parents=True, exist_ok=True)
    w, h = shots[0][1].size
    # Remotion's ffmpeg reads images through a pipe, not raw pixels: each frame goes as a BMP.
    ff = subprocess.Popen([
        str(FFMPEG), "-y", "-loglevel", "error", "-f", "image2pipe", "-c:v", "bmp", "-framerate", str(FPS), "-i", "-",
        "-vf", f"scale={w * SCALE}:{h * SCALE}:flags=lanczos", "-c:v", "libx264", "-preset", "slow", "-crf", "16", "-pix_fmt", "yuv420p",
        str(dst),
    ], stdin=subprocess.PIPE)
    k = 0
    for n in range(count):
        at = n * 1000 / FPS
        while k + 1 < len(shots) and shots[k + 1][0] <= at:
            k += 1
        buf = io.BytesIO()
        shots[k][1].save(buf, "BMP")
        ff.stdin.write(buf.getvalue())
    ff.stdin.close()
    if ff.wait():
        raise SystemExit(f"ffmpeg failed on {name}")
    print(f"{name}: {count} frames")

out = ROOT / "src" / "generated" / "showcase.ts"
out.write_text(
    "// Generated by tools/showcase.py from the assistants' showcase clips. Do not edit.\n"
    f"export const SHOWCASE: Record<string, number> = {json.dumps(lengths, indent=1)};\n",
    encoding="utf-8",
)
print(f"{len(lengths)} clips")
