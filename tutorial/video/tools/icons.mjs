// Collects the Fluent icons the scenes use («flash_24_filled»…) into src/generated/icons.ts, so the video carries
// only the few it needs. Run it after adding an icon: node tools/icons.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'node_modules', '@fluentui', 'svg-icons', 'icons');

const files = [];
const walk = dir => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) { if (name !== 'generated') walk(path); }
    else if (/\.(tsx?|json)$/.test(name)) files.push(path);
  }
};
walk(join(root, 'src'));

const names = new Set();
for (const file of files)
  for (const m of readFileSync(file, 'utf8').matchAll(/\b([a-z0-9]+(?:_[a-z0-9]+)*_(?:16|20|24|28|32|48)_(?:regular|filled))\b/g)) names.add(m[1]);

const icons = {};
const missing = [];
for (const name of [...names].sort()) {
  try {
    const svg = readFileSync(join(iconsDir, name + '.svg'), 'utf8');
    const size = Number(/viewBox="0 0 (\d+) \d+"/.exec(svg)?.[1] ?? 24);
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/fill="[^"]*"/g, '');
    icons[name] = { size, body: inner };
  } catch {
    missing.push(name);
  }
}
mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'src', 'generated', 'icons.ts'),
  '// Generated by tools/icons.mjs from @fluentui/svg-icons (MIT). Do not edit.\n' +
  `export const ICONS: Record<string, { size: number; body: string }> = ${JSON.stringify(icons, null, 1)};\n`);
console.log(`${Object.keys(icons).length} icons` + (missing.length ? `; missing: ${missing.join(', ')}` : ''));
